import type { Plugin } from 'vite';
import * as fs from 'node:fs';
import * as path from 'node:path';

interface MarkommerceBlock {
  extension: string;
  priority: number;
}

interface PackageJson {
  name?: string;
  markommerce?: MarkommerceBlock;
}

interface DiscoveredModule {
  name: string;
  priority: number;
  extensionPath: string;
}

interface PluginOptions {
  packagesPath?: string;
  outputPath?: string;
}

const FRONTEND_KERNEL = '@markommerce/frontend';

function discoverModules(packagesPath: string): DiscoveredModule[] {
  const entries = fs.readdirSync(packagesPath, { withFileTypes: true });
  const modules: DiscoveredModule[] = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }

    const pkgDir = path.join(packagesPath, entry.name);
    const pkgJsonPath = path.join(pkgDir, 'package.json');

    if (!fs.existsSync(pkgJsonPath)) {
      continue;
    }

    let pkgJson: PackageJson;
    try {
      pkgJson = JSON.parse(fs.readFileSync(pkgJsonPath, 'utf-8')) as PackageJson;
    } catch {
      continue;
    }

    if (!pkgJson.markommerce) {
      continue;
    }

    const name = pkgJson.name ?? entry.name;
    const { extension, priority } = pkgJson.markommerce;
    const extensionPath = path.resolve(pkgDir, extension);

    modules.push({ name, priority, extensionPath });
  }

  return modules;
}

function sortModules(modules: DiscoveredModule[]): DiscoveredModule[] {
  return [...modules].sort((a, b) => {
    if (a.name === FRONTEND_KERNEL) return -1;
    if (b.name === FRONTEND_KERNEL) return 1;

    if (a.priority !== b.priority) {
      return a.priority - b.priority;
    }

    return a.name.localeCompare(b.name);
  });
}

function generateFileContent(modules: DiscoveredModule[]): string {
  const lines: string[] = [];

  lines.push('// DO NOT EDIT — this file is generated by vite-plugin-markommerce.');
  lines.push('// Re-generated on every build and on package.json HMR updates.');
  lines.push('');

  for (const mod of modules) {
    lines.push(`import '${mod.extensionPath}';`);
  }

  lines.push('');
  lines.push('export const LOADED_MODULES = [');
  for (const mod of modules) {
    lines.push(`  { name: '${mod.name}', priority: ${mod.priority} },`);
  }
  lines.push('] as const;');
  lines.push('');

  return lines.join('\n');
}

function generateExtensionsFile(packagesPath: string, outputPath: string): void {
  const modules = discoverModules(packagesPath);
  const sorted = sortModules(modules);
  const content = generateFileContent(sorted);

  const outputDir = path.dirname(outputPath);
  fs.mkdirSync(outputDir, { recursive: true });
  fs.writeFileSync(outputPath, content, 'utf-8');
}

function isPackageJsonInPackagesPath(file: string, packagesPath: string): boolean {
  const normalized = path.normalize(file);
  const normalizedPackagesPath = path.normalize(packagesPath);

  // Match: packagesPath/<single-dir>/package.json
  const relative = path.relative(normalizedPackagesPath, normalized);
  const parts = relative.split(path.sep);

  return parts.length === 2 && parts[1] === 'package.json';
}

export default function markommerceModuleScanner(options?: PluginOptions): Plugin {
  const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
  const packagesPath = options?.packagesPath ?? path.join(repoRoot, 'packages');
  const outputPath =
    options?.outputPath ??
    path.join(
      repoRoot,
      'packages',
      'frontend-demo',
      'resources',
      'js',
      '.generated',
      'extensions.ts',
    );

  return {
    name: 'markommerce-module-scanner',

    async buildStart() {
      generateExtensionsFile(packagesPath, outputPath);
    },

    async handleHotUpdate({ file }: { file: string }) {
      if (isPackageJsonInPackagesPath(file, packagesPath)) {
        generateExtensionsFile(packagesPath, outputPath);
      }
    },
  };
}
